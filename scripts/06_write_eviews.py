"""
06_write_eviews.py — generate the EViews programs in /eviews from the specifications actually estimated
(lag orders, regressor order, samples), so EViews re-estimates exactly what the website reports.

Two routes are written for each dynamic model:
  (1) the native EViews ARDL estimator ("ardl" command), whose Long-Run Form/Bounds Test views are opened
      from the menus (see eviews/EVIEWS_EXECUTION_GUIDE.md);
  (2) an explicit OLS replication of the conditional error-correction regression and the levels ARDL, with the
      bounds F, long-run coefficients and symmetry restrictions computed by Wald tests. Its coefficient tables are
      exported to eviews/output/*.csv and checked by scripts/07_compare_eviews.py.
Run: python scripts/06_write_eviews.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "research" / "outputs"
EV = ROOT / "eviews"
EV.mkdir(exist_ok=True)
(EV / "output").mkdir(exist_ok=True)
SEAS = " ".join(f"seas{m:02d}" for m in range(1, 12))
Y = "lfoodcpi"

HEADER = """' =====================================================================================
' THE PRICE OF A FALLING RUPEE — EViews program {name}
' Generated by scripts/06_write_eviews.py from the specification estimated in Python.
' Run 00_master.prg, or run this file after 01_import.prg has created the workfile.
' =====================================================================================
"""


def cec_terms(xs, order):
    p, qs = order[0], order[1:]
    q = dict(zip(xs, qs))
    lev = [f"{Y}(-1)"] + [f"{x}(-1)" if q[x] > 0 else x for x in xs]
    sr = [f"d({Y}(-{i}))" for i in range(1, p)]
    for x in xs:
        sr += [f"d({x})" if l == 0 else f"d({x}(-{l}))" for l in range(q[x])]
    return lev, sr


def lev_terms(xs, order):
    p, qs = order[0], order[1:]
    terms = [f"{Y}(-{i})" for i in range(1, p + 1)]
    for x, qx in zip(xs, qs):
        terms += [x if l == 0 else f"{x}(-{l})" for l in range(qx + 1)]
    return terms


def export_block(eq, fname):
    return f"""
table tb_{eq}
tb_{eq}(1,1) = "position"
tb_{eq}(1,2) = "coef"
tb_{eq}(1,3) = "se"
for !i = 1 to {eq}.@ncoefs
  tb_{eq}(!i+1,1) = @str(!i)
  tb_{eq}(!i+1,2) = @str({eq}.@coefs(!i), "g15")
  tb_{eq}(!i+1,3) = @str({eq}.@stderrs(!i), "g15")
next
tb_{eq}.save(t=csv) "{{%out}}{fname}"
"""


def model_program(model_id, xs, order, start, fixed=SEAS, tag="main"):
    lev, sr = cec_terms(xs, order)
    k = len(xs)
    reg = " ".join(xs)
    eq = model_id.lower()
    nlev = len(lev)
    # coefficient positions in the CEC: c(1)=C, c(2)=y(-1), c(3..) = level regressors
    wald_bounds = ", ".join(f"c({i})=0" for i in range(2, 2 + nlev))
    lr_lines = "\n".join(f"freeze(tb_{eq}_lr_{x}) eq_{eq}_cec.wald -c({i + 3})/c(2) = 0   ' long-run coefficient of {x}"
                         for i, x in enumerate(xs))
    s = HEADER.format(name=f"{model_id}") + f"""
smpl {start} 2025m12
' ---- (1) Native EViews ARDL: automatic selection, AIC, max 4 lags, unrestricted constant (PSS case III)
'      Expected selected model: ARDL{tuple(order)}
equation eq_{eq}_native.ardl(deplags=4, reglags=4, ic=aic, trend=const) {Y} {reg} @ {fixed}
freeze(tb_{eq}_native) eq_{eq}_native.output
'      Then open: View > Coefficient Diagnostics > Long Run Form and Bounds Test
'                 View > Coefficient Diagnostics > Error Correction Form (or ECM Regression)

' ---- (2) Explicit OLS replication on the common sample (first {max(4, 0)} observations reserved for lags)
smpl 2015m05 2025m12
equation eq_{eq}_lev.ls {Y} c {" ".join(lev_terms(xs, order))} {fixed}
equation eq_{eq}_cec.ls d({Y}) c {" ".join(lev)} {" ".join(sr)} {fixed}

' PSS bounds F-test (case III, k = {k}): H0 all level coefficients = 0 -> compare F with I(0)/I(1) bounds
freeze(tb_{eq}_bounds) eq_{eq}_cec.wald {wald_bounds}
' PSS t-test = t-statistic on c(2) in eq_{eq}_cec

' Long-run coefficients L = -theta/rho with delta-method standard errors
{lr_lines}

' Diagnostics on the levels ARDL
freeze(tb_{eq}_bg2) eq_{eq}_lev.auto(2)
freeze(tb_{eq}_bg12) eq_{eq}_lev.auto(12)
freeze(tb_{eq}_bpg) eq_{eq}_lev.hettest(type=bpg)
freeze(tb_{eq}_white) eq_{eq}_lev.hettest(type=white)
freeze(tb_{eq}_arch1) eq_{eq}_lev.hettest(type=arch, lags=1)
freeze(tb_{eq}_arch12) eq_{eq}_lev.hettest(type=arch, lags=12)
freeze(tb_{eq}_reset) eq_{eq}_lev.reset(1)
eq_{eq}_lev.makeresids res_{eq}
freeze(tb_{eq}_jb) res_{eq}.hist
freeze(gr_{eq}_cusum) eq_{eq}_lev.rls(q)
freeze(gr_{eq}_cusumsq) eq_{eq}_lev.rls(v)
gr_{eq}_cusum.save(t=png) "{{%out}}{eq}_cusum.png"
gr_{eq}_cusumsq.save(t=png) "{{%out}}{eq}_cusumsq.png"
"""
    s += export_block(f"eq_{eq}_cec", f"{eq}_cec.csv")
    s += export_block(f"eq_{eq}_lev", f"{eq}_lev.csv")
    return s


ardl = json.loads((OUT / "ardl_results.json").read_text())
nardl = json.loads((OUT / "nardl_results.json").read_text())
rob = json.loads((OUT / "robustness.json").read_text())
X_A = ["lexr", "lgfood", "ltranscpi"]
X_N = ["lexr_pos", "lexr_neg", "lgfood", "ltranscpi"]

files = {}
files["01_import.prg"] = HEADER.format(name="01_import") + """
' Creates a monthly workfile 2015M01–2025M12 and imports the processed dataset.
%path = @runpath
cd %path
wfcreate(wf=falling_rupee, page=monthly) m 2015m01 2025m12
import(page=monthly) "..\\data\\processed\\estimation_sample.xlsx" range="data" colhead=1 @freq m 2015m01 @smpl @all
' sanity checks: N = 132, partial sums reconstruct ln EXR
series chk_ps = lexr - (@elem(lexr, "2015m01") + lexr_pos + lexr_neg)
scalar chk_ps_max = @max(@abs(chk_ps))
scalar chk_nobs = @obs(lfoodcpi)
group g_core lfoodcpi lexr lgfood ltranscpi
group g_levels foodcpi exr gfood transcpi
group g_nardl lexr_pos lexr_neg
wfsave falling_rupee.wf1
"""
files["02_descriptives_unitroots.prg"] = HEADER.format(name="02_descriptives_unitroots") + """
smpl @all
freeze(tb_desc) g_levels.stats
group g_rates food_inf_yoy food_inf_mom exr_dep_yoy gfood_yoy trans_yoy
freeze(tb_desc_rates) g_rates.stats
freeze(tb_cor_levels) g_core.cor
group g_dcore d(lfoodcpi) d(lexr) d(lgfood) d(ltranscpi)
freeze(tb_cor_diff) g_dcore.cor
' Unit-root battery: ADF (AIC and SIC, max 12 lags), PP, KPSS — levels (const; const+trend), 1st and 2nd differences
for %v lfoodcpi lexr lgfood ltranscpi lexr_pos lexr_neg lhouscpi lbrent lgfood_wb
  for %ic aic sic
    freeze(ur_{%v}_adf_c_{%ic}) {%v}.uroot(adf, const, info={%ic}, maxlag=12)
    freeze(ur_{%v}_adf_t_{%ic}) {%v}.uroot(adf, trend, info={%ic}, maxlag=12)
    freeze(ur_{%v}_adf_d1_{%ic}) {%v}.uroot(adf, const, info={%ic}, maxlag=12, dif=1)
    freeze(ur_{%v}_adf_d2_{%ic}) {%v}.uroot(adf, const, info={%ic}, maxlag=12, dif=2)
  next
  freeze(ur_{%v}_pp_c) {%v}.uroot(pp, const)
  freeze(ur_{%v}_pp_t) {%v}.uroot(pp, trend)
  freeze(ur_{%v}_pp_d1) {%v}.uroot(pp, const, dif=1)
  freeze(ur_{%v}_kpss_c) {%v}.uroot(kpss, const)
  freeze(ur_{%v}_kpss_d1) {%v}.uroot(kpss, const, dif=1)
next
"""
files["03_ols.prg"] = HEADER.format(name="03_ols") + """
smpl @all
equation eq_ols.ls lfoodcpi c lexr lgfood ltranscpi
equation eq_ols_hac.ls(cov=hac) lfoodcpi c lexr lgfood ltranscpi
freeze(tb_ols_vif) eq_ols.varinf
freeze(tb_ols_bg2) eq_ols.auto(2)
freeze(tb_ols_bpg) eq_ols.hettest(type=bpg)
freeze(tb_ols_reset) eq_ols.reset(1)
' Engle-Granger residual-based cointegration test
freeze(tb_ols_eg) g_core.coint(method=eg, trend=const)
' First-difference regression (HAC)
equation eq_ols_d.ls(cov=hac) d(lfoodcpi) c d(lexr) d(lgfood) d(ltranscpi)
""" + export_block("eq_ols", "ols.csv")
files["04_ardl.prg"] = model_program("ARDL_MAIN", X_A, ardl["selection"]["chosen_order"], "2015m01")
files["05_nardl.prg"] = model_program("NARDL_MAIN", X_N, nardl["selection"]["chosen_order"], "2015m01") + """
' ---- NARDL asymmetry tests
' Long-run symmetry: H0 -c(3)/c(2) = -c(4)/c(2)  (LEXR_POS and LEXR_NEG are the 3rd and 4th CEC coefficients)
freeze(tb_nardl_lrsym) eq_nardl_main_cec.wald c(3)/c(2) = c(4)/c(2)
freeze(tb_nardl_lrsym_lin) eq_nardl_main_cec.wald c(3) = c(4)
' Impact (short-run) symmetry on the levels ARDL: beta+_0 = beta-_0
'   levels coefficients: c(1)=C, c(2)=LFOODCPI(-1), c(3)=LEXR_POS, c(4)=LEXR_NEG, c(5)=LEXR_NEG(-1), ...
freeze(tb_nardl_impact) eq_nardl_main_lev.wald c(3) = c(4)
' Dynamic multipliers are computed from the levels ARDL coefficients in scripts/ardl_engine.py
' (multipliers.json); in EViews they can be reproduced with the NARDL add-in if it is installed.
"""
# robustness programs (explicit OLS route only, one CEC per spec)
rb = [HEADER.format(name="06_robustness")]
spec_x = {"BASE": X_N, "SIC": X_N, "HQ": X_N, "LAG6": X_N, "ENERGY_HOUS": ["lexr_pos", "lexr_neg", "lgfood", "lhouscpi"],
          "ENERGY_BRENT": ["lexr_pos", "lexr_neg", "lgfood", "lbrent"], "GFOOD_WB": ["lexr_pos", "lexr_neg", "lgfood_wb", "ltranscpi"],
          "EVENTS": X_N, "IMPULSE": X_N, "NOSEAS": X_N, "PRE2024": X_N, "POST_REBASE": X_N, "HEADLINE": X_N}
spec_fixed = {"EVENTS": SEAS + " d_rebase d_covid d_flood d_ramadan", "IMPULSE": SEAS + " d_2024m05", "NOSEAS": ""}
spec_smpl = {"LAG6": ("2015m07", "2025m12"), "PRE2024": ("2015m05", "2023m12"), "POST_REBASE": ("2019m10", "2025m12")}
rb.append('series d_2024m05 = @date = @dateval("2024m05")\n')
for r in rob["nardl_specifications"]:
    if "order" not in r:
        continue
    sid = r["id"]
    xs = spec_x[sid]
    yv = "lcpi" if sid == "HEADLINE" else Y
    lev, sr = cec_terms(xs, r["order"])
    if yv != Y:
        lev = [t.replace(Y, yv) for t in lev]
        sr = [t.replace(Y, yv) for t in sr]
    a, b = spec_smpl.get(sid, ("2015m05", "2025m12"))
    fx = spec_fixed.get(sid, SEAS)
    rb.append(f"""' --- {sid}: {r['label']} — Python: ARDL{tuple(r['order'])}, F = {r['bounds_F']}, t = {r['bounds_t']}
smpl {a} {b}
equation eq_r_{sid.lower()}.ls d({yv}) c {" ".join(lev)} {" ".join(sr)} {fx}
freeze(tb_r_{sid.lower()}_bounds) eq_r_{sid.lower()}.wald {", ".join(f"c({i})=0" for i in range(2, 2 + len(lev)))}
freeze(tb_r_{sid.lower()}_lrsym) eq_r_{sid.lower()}.wald c(3)/c(2) = c(4)/c(2)
""")
rb.append("smpl @all\n")
files["06_robustness.prg"] = "\n".join(rb)
files["00_master.prg"] = HEADER.format(name="00_master") + """
' Runs the whole EViews workflow. Outputs (CSV coefficient tables, PNG stability graphs) go to eviews/output/.
%path = @runpath
cd %path
%out = %path + "output\\"
include 01_import.prg
include 02_descriptives_unitroots.prg
include 03_ols.prg
include 04_ardl.prg
include 05_nardl.prg
include 06_robustness.prg
smpl @all
wfsave falling_rupee.wf1
"""
for name, txt in files.items():
    (EV / name).write_text(txt, encoding="utf-8")
    print("  eviews/" + name)
